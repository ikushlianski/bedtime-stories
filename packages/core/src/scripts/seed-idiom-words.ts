async function seed() {
  let inserted = 0
  let skipped = 0

  for (const { word, hint } of IDIOMS) {
    const existing = await db
      .select({ id: words.id })
      .from(words)
      .where(sql`lower(${words.word}) = lower(${word})`)
      .limit(1)

    if (existing.length > 0) {
      skipped++
      continue
    }

    await db.insert(words).values({ word, hint, universeId: null })
    inserted++
  }

  console.log(`Seeded ${inserted} idiom words, skipped ${skipped} already present (of ${IDIOMS.length} total).`)
  process.exit(0)
}

seed()
