export function selectStorySetting(storyId?: number): StorySetting {
  const index =
    storyId !== undefined && storyId >= 0
      ? (storyId * 11) % STORY_SETTINGS.length
      : Math.floor(Math.random() * STORY_SETTINGS.length)

  return STORY_SETTINGS[index] as StorySetting
}

