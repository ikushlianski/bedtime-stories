export function selectVoiceRegister(storyId?: number): VoiceRegister {
  const index =
    storyId !== undefined && storyId >= 0
      ? storyId % VOICE_REGISTERS.length
      : Math.floor(Math.random() * VOICE_REGISTERS.length)

  return VOICE_REGISTERS[index] as VoiceRegister
}

export function getVoiceRegisterByKey(key: string): VoiceRegister | undefined {
  return VOICE_REGISTERS.find((voice) => voice.key === key)
}

export function buildVoiceBlock(voice: VoiceRegister): string {
  return [
    '\n\n---',
    'ГОЛОС РАССКАЗЧИКА ИМЕННО ЭТОЙ ИСТОРИИ (выбор уже сделан — веди повествование именно в этой манере, не смешивай с другими):',
    `Регистр: ${voice.title}`,
    `Как звучит: ${voice.description}`,
    'Это про интонацию и ритм повествования, а не про сюжет или структуру — следуй ему на уровне фраз и подачи, не меняя плана истории.',
    '---\n',
  ].join('\n')
}
