export function selectCharacterLens(storyId?: number): CharacterLens {
  const index =
    storyId !== undefined && storyId >= 0
      ? (storyId * 3) % CHARACTER_LENSES.length
      : Math.floor(Math.random() * CHARACTER_LENSES.length)

  return CHARACTER_LENSES[index] as CharacterLens
}

export function buildCharacterLensBlock(lens: CharacterLens): string {
  return [
    '\n\n---',
    'РАКУРС НА ПЕРСОНАЖЕЙ ДЛЯ ЭТОЙ ИСТОРИИ (чтобы истории не были похожи одна на другую):',
    `Ракурс: ${lens.title}`,
    lens.guidance,
    '',
    'Как этим пользоваться:',
    '- Обязательные роли остаются (есть смешной/чудаковатый персонаж; есть тот, кто держит противоположное мнение и не сдаётся сразу) — но КТО именно их играет, меняй от истории к истории. Не отдавай смешную роль всё время одному и тому же персонажу.',
    '- Меняй состав: не тот же набор лиц, что в соседних историях. Тасуй, кого берёшь из ростера вселенной, и как они себя ведут.',
    '- Меняй поведение Гоши: он не обязан всегда быть в центре, всегда быть правым или всегда первым действовать.',
    'ГРАНИЦА (важно): бери ТОЛЬКО тех персонажей, кто по канону и по месту действия реально может здесь оказаться. Возраст, садиковская группа, кто где живёт и учится — всё это соблюдай строго. Не притягивай персонажа в сцену, где его быть не может, ради разнообразия.',
    '---\n',
  ].join('\n')
}
